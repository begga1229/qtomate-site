export function makeT(lang) {
  const i = Math.max(0, LANGS.indexOf(lang));
  return function t(key, vars) {
    const entry = T[key];
    let s = entry ? entry[i] : key;
    if (vars) for (const k in vars) s = s.replace("{" + k + "}", vars[k]);
    return s;
  };
}
